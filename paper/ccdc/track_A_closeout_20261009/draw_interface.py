def box(x,y,w,h,text,color='#f4f6f8',size=7.4):
    ax.add_patch(FancyBboxPatch((x,y),w,h,boxstyle='round,pad=.004',facecolor=color,edgecolor='#334b60',linewidth=.65))
    ax.text(x+w/2,y+h/2,text,ha='center',va='center',linespacing=1.1,fontsize=size)
def path(points, dashed=False):
    xs,ys=zip(*points)
